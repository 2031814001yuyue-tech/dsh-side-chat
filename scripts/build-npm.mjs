/**
 * 生成 npm 安装用的 lib/ 产物（单一事实源 = src/host.js + src/client.js）。
 *
 * 两条安装路径共用同一份业务逻辑：
 *   - 动态插件（cordis_define/cordis_run）：直接以函数体加载 src/*.js，
 *     runner 提供 builtin（harness / React / host / styles / timer）。
 *   - npm 静态安装（cordis.patch.yml 加一行）：Host 走 lib/index.js
 *     （harness.handle → webServer 路由适配器）；Client 走 lib/client.js
 *     （__ModuleLoader__ 包装 + React(require)/host(fetch)/styles(DOM) shim）。
 *
 * 产物内联源码（JSON 字符串），发布后不依赖 src/ 存在；改动 src/*.js 后
 * 必须重新运行 `npm run build` 再发布。
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const libDir = join(root, 'lib')

const hostSource = readFileSync(join(root, 'src', 'host.js'), 'utf8')
const clientSource = readFileSync(join(root, 'src', 'client.js'), 'utf8')

// ---------------------------------------------------------------------------
// lib/index.js — Host 适配器（CommonJS，cordis 插件工厂 + inject）
// ---------------------------------------------------------------------------
// 动态路径里 host.js 的 apply() 闭包引用了 runner 的 `harness` builtin
// （harness.handle(method, handler) 注册 Package-private RPC）。静态路径没有
// harness，这里用 webServer 路由实现同一接口：每个 method 注册一条 exact 路由
// /sidechat-api/<method>，请求体 JSON 即 RPC args，响应体 JSON 即 RPC 结果。
// 路由注册挂在 ctx.effect 上，插件卸载时随 fiber 一起回收。
const hostTemplate = `'use strict'

/**
 * GENERATED by scripts/build-npm.mjs — do not edit by hand.
 * npm 安装路径的 Host 适配器：把动态插件的 harness.handle RPC 桥接到
 * webServer 路由（/sidechat-api/<method>）。业务逻辑与 src/host.js 完全同源。
 */

const HOST_SOURCE = ${JSON.stringify(hostSource)}

function makeHarness(ctx, apiBase) {
  const webServer = ctx.get('webServer')
  return {
    handle(method, handler) {
      ctx.effect(() => webServer.register({
        kind: 'exact',
        path: apiBase + method,
        handler: async (req, res) => {
          try {
            const args = await readJsonBody(req)
            const result = await handler(args)
            sendJson(res, 200, result)
          } catch (err) {
            console.error('[side-chat]', method, 'failed:', err && err.message || err)
            sendJson(res, 500, { ok: false, error: String((err && err.message) || err) })
          }
        },
      }), 'side-chat: route ' + method)
    },
  }
}

function readJsonBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = []
    req.on('data', (chunk) => chunks.push(chunk))
    req.on('end', () => {
      if (chunks.length === 0) {
        resolve({})
        return
      }
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')))
      } catch (err) {
        reject(new Error('请求体不是合法 JSON：' + err.message))
      }
    })
    req.on('error', reject)
  })
}

function sendJson(res, status, value) {
  const body = JSON.stringify(value)
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
  })
  res.end(body)
}

function sideChatHost(ctx) {
  const harness = makeHarness(ctx, '/sidechat-api/')
  const plugin = new Function('harness', HOST_SOURCE)(harness)
  plugin.apply(ctx)
}

sideChatHost.inject = ['webServer']

module.exports = sideChatHost
`

// ---------------------------------------------------------------------------
// lib/client.js — Client 半体（__ModuleLoader__ 包装，浏览器 bundle）
// ---------------------------------------------------------------------------
// 官方 client bundle 格式：window.__ModuleLoader__.load({ id, factory })，
// id 必须等于 loader 条目名（包名），factory(require) 返回 { apply, inject }。
// 静态路径没有动态 runner 的 builtin，这里用 shim 补齐：
//   React  —— require('react')（loader 的 seed word，官方 bundle 同款）
//   host   —— fetch 直连 /sidechat-api/<method>（webServer 路由）
//   styles —— DOM <style> 注入
//   timer  —— src/client.js 内置 setInterval 回退（已改）
const clientTemplate = `// GENERATED by scripts/build-npm.mjs — do not edit by hand.
// npm 安装路径的 Client 半体：__ModuleLoader__ 包装 + 浏览器 shim，
// 业务逻辑与 src/client.js 完全同源。
window.__ModuleLoader__.load({
  id: 'dsh-side-chat',
  factory: (require) => {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    const React = require('react')

    const INJECT = ['@deepseek-ai/dsh-client-runtime']

    // host shim：动态 runner 的 host builtin 在静态路径不存在，
    // 改走 Host 半体注册的 webServer 路由（见 lib/index.js）。
    const host = {
      call: async (method, args) => {
        const res = await fetch('/sidechat-api/' + method, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(args || {}),
        })
        if (!res.ok) {
          let detail = ''
          try {
            const parsed = await res.json()
            detail = (parsed && parsed.error) || ''
          } catch (err) {
            /* 非 JSON 错误体：保留状态码 */
          }
          throw new Error(detail || ('HTTP ' + res.status))
        }
        return res.json()
      },
    }

    // styles shim：动态 runner 的 styles.insert 在静态路径不存在，改 DOM 注入
    const styles = {
      insert(css) {
        const tag = document.createElement('style')
        tag.setAttribute('data-plugin', 'dsh-side-chat')
        tag.textContent = css
        document.head.appendChild(tag)
      },
    }

    const CLIENT_SOURCE = ${JSON.stringify(clientSource)}

    const makePlugin = new Function('React', 'host', 'styles', 'console', CLIENT_SOURCE)
    const plugin = makePlugin(React, host, styles, console)

    exports.apply = plugin.apply
    exports.inject = INJECT
    return module.exports
  },
})
`

mkdirSync(libDir, { recursive: true })
writeFileSync(join(libDir, 'index.js'), hostTemplate, 'utf8')
writeFileSync(join(libDir, 'client.js'), clientTemplate, 'utf8')

console.log('[build-npm] lib/index.js  (%d bytes)', Buffer.byteLength(hostTemplate))
console.log('[build-npm] lib/client.js (%d bytes)', Buffer.byteLength(clientTemplate))
